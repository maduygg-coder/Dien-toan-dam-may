
from pathlib import Path
from datetime import time
import os

import psycopg
from psycopg.rows import dict_row
from dotenv import load_dotenv
from flask import Flask, render_template, request, redirect, url_for

load_dotenv(Path(__file__).resolve().parent / ".env")
app = Flask(__name__)

DAYS = ["Thứ 2", "Thứ 3", "Thứ 4", "Thứ 5",
        "Thứ 6", "Thứ 7", "Chủ nhật"]
FIELDS = ("subject", "day", "start_time", "end_time", "room")


def get_db():
    return psycopg.connect(
        host=os.environ.get("POSTGRES_HOST", "127.0.0.1"),
        port=os.environ.get("POSTGRES_PORT", "5432"),
        dbname=os.environ.get("POSTGRES_DB", "cloudtask"),
        user=os.environ.get("POSTGRES_USER", "cloudtask"),
        password=os.environ["POSTGRES_PASSWORD"],
        row_factory=dict_row,
        connect_timeout=10,
    )


def init_db():
    with get_db() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS schedules (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                subject TEXT NOT NULL,
                day TEXT NOT NULL,
                start_time TEXT NOT NULL,
                end_time TEXT NOT NULL,
                room TEXT NOT NULL
            )
        """)


init_db()


def get_schedules(conn):
    return conn.execute(
        "SELECT * FROM schedules ORDER BY id DESC"
    ).fetchall()


def read_form():
    return {
        key: request.form.get(key, "").strip()
        for key in FIELDS
    }


def validate(data):
    if not all(data.values()):
        return "Vui lòng nhập đầy đủ thông tin."

    if data["day"] not in DAYS:
        return "Thứ học không hợp lệ."

    try:
        start = time.fromisoformat(data["start_time"])
        end = time.fromisoformat(data["end_time"])
    except ValueError:
        return "Giờ học không hợp lệ."

    if start >= end:
        return "Giờ kết thúc phải sau giờ bắt đầu."

    return None


def find_conflict(conn, data, exclude_id=None):
    query = """
        SELECT *
        FROM schedules
        WHERE day = %s
          AND start_time < %s
          AND end_time > %s
    """
    params = [data["day"], data["end_time"], data["start_time"]]

    if exclude_id is not None:
        query += " AND id <> %s"
        params.append(exclude_id)

    query += " LIMIT 1"
    return conn.execute(query, params).fetchone()


def conflict_message(conflict):
    return (
        f"Lịch này trùng với môn {conflict['subject']} "
        f"({conflict['start_time']} - {conflict['end_time']}). "
        "Vui lòng chọn khung giờ khác."
    )


@app.route("/")
def home():
    with get_db() as conn:
        schedules = get_schedules(conn)
    return render_template("index.html", schedules=schedules)


@app.route("/schedules/add", methods=["POST"])
def add_schedule():
    data = read_form()
    error = validate(data)

    if error:
        with get_db() as conn:
            schedules = get_schedules(conn)
        return render_template(
            "index.html", schedules=schedules,
            error=error, form=data
        ), 400

    with get_db() as conn:
        conn.execute(
            "SELECT pg_advisory_xact_lock(hashtext(%s))",
            (data["day"],)
        )
        conflict = find_conflict(conn, data)

        if conflict:
            schedules = get_schedules(conn)
            return render_template(
                "index.html", schedules=schedules,
                error=conflict_message(conflict), form=data
            ), 409

        conn.execute("""
            INSERT INTO schedules
            (subject, day, start_time, end_time, room)
            VALUES (%s, %s, %s, %s, %s)
        """, tuple(data[key] for key in FIELDS))

    return redirect(url_for("home"))


@app.route("/schedules/<int:schedule_id>/edit", methods=["GET", "POST"])
def edit_schedule(schedule_id):
    with get_db() as conn:
        schedule = conn.execute(
            "SELECT * FROM schedules WHERE id = %s",
            (schedule_id,)
        ).fetchone()

    if schedule is None:
        return "Không tìm thấy lịch học.", 404

    if request.method == "GET":
        return render_template("edit.html", schedule=schedule)

    data = read_form()
    error = validate(data)

    if error:
        return render_template(
            "edit.html",
            schedule={"id": schedule_id, **data},
            error=error
        ), 400

    with get_db() as conn:
        conn.execute(
            "SELECT pg_advisory_xact_lock(hashtext(%s))",
            (data["day"],)
        )
        conflict = find_conflict(conn, data, schedule_id)

        if conflict:
            return render_template(
                "edit.html",
                schedule={"id": schedule_id, **data},
                error=conflict_message(conflict)
            ), 409

        conn.execute("""
            UPDATE schedules
            SET subject=%s, day=%s, start_time=%s,
                end_time=%s, room=%s
            WHERE id=%s
        """, (*[data[key] for key in FIELDS], schedule_id))

    return redirect(url_for("home"))


@app.route("/schedules/<int:schedule_id>/delete", methods=["POST"])         
def delete_schedule(schedule_id):
    with get_db() as conn:
        result = conn.execute(
            "DELETE FROM schedules WHERE id = %s",
            (schedule_id,)
        )
        if result.rowcount == 0:
            return "Không tìm thấy lịch học.", 404

    return redirect(url_for("home"))


@app.route("/health")
def health():
    return {"status": "ok", "app": "StudySchedule Cloud"}, 200


if __name__ == "__main__":
    port = int(os.environ.get("PORT", "5000"))
    app.run(host="0.0.0.0", port=port, debug=False)
